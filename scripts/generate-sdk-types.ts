import { readFileSync, writeFileSync } from 'node:fs'

type GenerationTarget = {
  schemaPath: string
  outputPath: string
  prelude?: string
}

const targets: GenerationTarget[] = [
  {
    schemaPath: 'src/entrypoints/sdk/coreSchemas.ts',
    outputPath: 'src/entrypoints/sdk/coreTypes.generated.ts',
  },
  {
    schemaPath: 'src/entrypoints/sdk/controlSchemas.ts',
    outputPath: 'src/entrypoints/sdk/controlTypes.ts',
    prelude: "export * from './coreTypes.js'\n\n",
  },
]

export function generateSdkTypes(): void {
  for (const target of targets) {
    const source = readFileSync(target.schemaPath, 'utf8')
    const schemaNames = Array.from(
      source.matchAll(/^export const (\w+Schema)\s*=/gm),
      match => match[1],
    )

    if (schemaNames.length === 0) {
      throw new Error(`No exported schemas found in ${target.schemaPath}`)
    }

    const declarations = schemaNames.map(schemaName => {
      const typeName = schemaName.slice(0, -'Schema'.length)
      return `export type ${typeName} = z.infer<\n  ReturnType<typeof schemas.${schemaName}>\n>`
    })

    const output = `// Generated by scripts/generate-sdk-types.ts. Do not edit directly.\nimport type { z } from 'zod'\nimport type * as schemas from './${target.schemaPath.split('/').pop()?.replace(/\.ts$/, '.js')}'\n\n${target.prelude ?? ''}${declarations.join('\n\n')}\n`

    writeFileSync(target.outputPath, output)
    console.log(`Generated ${target.outputPath} (${schemaNames.length} types)`)
  }
}

if (import.meta.main) {
  generateSdkTypes()
}
