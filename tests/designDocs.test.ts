const files = [
  'src/index.ts',
  'src/generated.ts',
  'tests/system.test.ts',
  'scripts/build.ts',
]

function createCompleteFixture(): void {
  put(MANIFEST_PATH, stringify(manifest()))
  put('docs/architecture/coverage/system.yaml', stringify(coverage()))
  put('docs/superpowers/specs/system-design.md', specText())
  put(INDEX_PATH, '# Architecture\n\n[System](../superpowers/specs/system-design.md)\n')
  put('src/index.ts', 'export {}\n')
  put('src/generated.ts', '// generated fixture\n')
  put('tests/system.test.ts', '// test fixture\n')
  put('scripts/build.ts', '// build fixture\n')
}

test('accepts a complete approved and linked fixture', async () => {
  createCompleteFixture()
  const result = await checkDesignDocs({ cwd, files })
  expect(result).toEqual({ errors: [], warnings: [] })
})

test('rejects metadata, section, backlink, INDEX, and Markdown failures', async () => {
  createCompleteFixture()
  put(
    'docs/superpowers/specs/system-design.md',
    specText()
      .replace('id: system', 'id: other')
      .replace('batch: 0', 'batch: 99')
      .replace('status: approved', 'status: draft')
      .replace('## 2. 设计理由与备选方案', '## 2. Wrong')
      .replace('../../architecture/coverage/system.yaml', '../../architecture/coverage/missing.yaml'),
  )
  put(INDEX_PATH, '# Architecture\n\n[Missing](missing-spec.md)\n')

  const result = await checkDesignDocs({ cwd, files })
  const codes = result.errors.map(issue => issue.code)
  for (const code of [
    'SPEC_METADATA',
    'MISSING_SECTION',
    'SPEC_COVERAGE_LINK',
    'INDEX_SPEC_LINK',
    'BROKEN_LINK',
  ]) {
    expect(codes).toContain(code)
  }
  // Check for field-specific messages in SPEC_METADATA
  const metadataError = result.errors.find(e => e.code === 'SPEC_METADATA')
  expect(metadataError?.message).toContain('id: expected "system", got "other"')
  expect(metadataError?.message).toContain('batch: expected 0, got 99')
  expect(metadataError?.message).toContain('status: expected "approved", got "draft"')
})

test('allows artifact-free planned entries normally and rejects them strictly', async () => {
  createCompleteFixture()
  const value = manifest()
  value.specs.push({
    id: 'future',
    spec: 'docs/superpowers/specs/future-design.md',
    coverage: 'docs/architecture/coverage/future.yaml',
    batch: 1,
    status: 'planned',
  })
  put(MANIFEST_PATH, stringify(value))

  const normal = await checkDesignDocs({ cwd, files })
  const strict = await checkDesignDocs({ cwd, files, requireApproved: true })
  expect(normal.errors).toEqual([])
  expect(normal.warnings.map(issue => issue.code)).toContain('PLANNED_SPEC')
  expect(strict.errors.map(issue => issue.code)).toContain('PLANNED_SPEC')
})

test('handles percent signs in documentation links without throwing', async () => {
  createCompleteFixture()
  // Add a file with percent signs and link to it from the spec
  put('docs/superpowers/specs/50% done.md', 'Progress file content')
  put(
    'docs/superpowers/specs/system-design.md',
    specText() + '\n\nSee [50% done](50% done.md) for progress.',
  )

  // Should not throw and should have no errors about the link
  const result = await checkDesignDocs({ cwd, files })
  expect(result.errors).toEqual([])
})

test('reports MISSING_INDEX but continues validating specs when INDEX.md is absent', async () => {
  createCompleteFixture()
  // Remove INDEX.md
  rmSync(join(cwd, INDEX_PATH))
  // Also modify the spec to have a metadata mismatch to test that validation still runs
  put(
    'docs/superpowers/specs/system-design.md',
    specText().replace('id: system', 'id: wrong-id'),
  )

  const result = await checkDesignDocs({ cwd, files })
  const codes = result.errors.map(issue => issue.code)
  expect(codes).toContain('MISSING_INDEX')
  expect(codes).toContain('SPEC_METADATA')
  expect(codes).toContain('INDEX_SPEC_LINK') // Because indexContent is empty, the link is missing
})

test('repository documentation registry has no structural errors', async () => {
  const repositoryRoot = resolve(import.meta.dir, '..')
  const result = await checkDesignDocs({ cwd: repositoryRoot })
  expect(result.errors).toEqual([])

  const sdkTypes = await loadCoverage(
    repositoryRoot,
    'docs/architecture/coverage/sdk-type-generation.yaml',
  )
  const ownedFiles = sdkTypes.groups.flatMap(group => group.files)
  expect(ownedFiles).toContain('src/entrypoints/sdk/settingsTypes.generated.ts')
  expect(result.warnings).not.toContainEqual({
    code: 'UNCOVERED_FILE',
    message: 'File has no primary spec or exclusion: src/entrypoints/sdk/settingsTypes.generated.ts',
  })
})

