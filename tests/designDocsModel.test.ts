import { afterEach, beforeEach, expect, test } from 'bun:test'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { stringify } from 'yaml'
import { loadCoverage, loadManifest } from '../scripts/check-design-docs.ts'

let cwd: string

beforeEach(() => {
  cwd = mkdtempSync(join(tmpdir(), 'design-docs-model-'))
})

afterEach(() => {
  rmSync(cwd, { recursive: true, force: true })
})

function put(path: string, content: string): void {
  const absolute = join(cwd, path)
  mkdirSync(dirname(absolute), { recursive: true })
  writeFileSync(absolute, content)
}

function manifest(): Record<string, unknown> {
  return {
    schema_version: 1,
    roots: ['src', 'tests', 'scripts'],
    specs: [{
      id: 'system',
      spec: 'docs/superpowers/specs/system-design.md',
      coverage: 'docs/architecture/coverage/system.yaml',
      batch: 0,
      status: 'approved',
    }],
    exclusions: [{
      glob: 'src/generated.ts',
      reason: 'Generated by the fixture generator.',
      source_spec: 'system',
    }],
  }
}

function coverage(): Record<string, unknown> {
  return {
    schema_version: 1,
    spec_id: 'system',
    spec: '../../superpowers/specs/system-design.md',
    status: 'approved',
    groups: [{
      id: 'source',
      kind: 'source',
      section: 4,
      summary: 'Fixture source.',
      files: ['src/index.ts'],
    }],
  }
}

test('loads valid manifest and coverage contracts', async () => {
  put('docs/architecture/coverage/manifest.yaml', stringify(manifest()))
  put('docs/architecture/coverage/system.yaml', stringify(coverage()))

  const loadedManifest = await loadManifest(cwd)
  const loadedCoverage = await loadCoverage(
    cwd,
    'docs/architecture/coverage/system.yaml',
  )

  expect(loadedManifest.specs[0]?.id).toBe('system')
  expect(loadedManifest.roots).toEqual(['src', 'tests', 'scripts'])
  expect(loadedCoverage.groups[0]?.files).toEqual(['src/index.ts'])
})

test('rejects malformed coverage groups with their field path', async () => {
  // Test invalid section
  const invalidSection = coverage()
  invalidSection.groups = [{
    id: 'good-id',
    kind: 'source',
    section: 10,
    summary: 'Valid summary',
    files: ['src/index.ts'],
  }]
  put('docs/architecture/coverage/system.yaml', stringify(invalidSection))
  await expect(loadCoverage(cwd, 'docs/architecture/coverage/system.yaml')).rejects.toThrow('groups.0.section')

  // Test invalid id
  const invalidId = coverage()
  invalidId.groups = [{
    id: 'Bad-ID!',
    kind: 'source',
    section: 4,
    summary: 'Valid summary',
    files: ['src/index.ts'],
  }]
  put('docs/architecture/coverage/system.yaml', stringify(invalidId))
  await expect(loadCoverage(cwd, 'docs/architecture/coverage/system.yaml')).rejects.toThrow('groups.0.id')

  // Test invalid kind
  const invalidKind = coverage()
  invalidKind.groups = [{
    id: 'good-id',
    kind: 'invalid-kind',
    section: 4,
    summary: 'Valid summary',
    files: ['src/index.ts'],
  }]
  put('docs/architecture/coverage/system.yaml', stringify(invalidKind))
  await expect(loadCoverage(cwd, 'docs/architecture/coverage/system.yaml')).rejects.toThrow('groups.0.kind')

  // Test empty summary
  const invalidSummary = coverage()
  invalidSummary.groups = [{
    id: 'good-id',
    kind: 'source',
    section: 4,
    summary: '',
    files: ['src/index.ts'],
  }]
  put('docs/architecture/coverage/system.yaml', stringify(invalidSummary))
  await expect(loadCoverage(cwd, 'docs/architecture/coverage/system.yaml')).rejects.toThrow('groups.0.summary')

  // Test empty files
  const invalidFiles = coverage()
  invalidFiles.groups = [{
    id: 'good-id',
    kind: 'source',
    section: 4,
    summary: 'Valid summary',
    files: [],
  }]
  put('docs/architecture/coverage/system.yaml', stringify(invalidFiles))
  await expect(loadCoverage(cwd, 'docs/architecture/coverage/system.yaml')).rejects.toThrow('groups.0.files')
})
